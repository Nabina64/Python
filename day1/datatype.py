# Tuple: () used to define tuple,multiple data of multiple datatype can be defined ,ordered,immutable(unchangable)
my_tuple = ("hello",15,35.5,True,None,"50")
print(my_tuple)

# Set: {} used to define set,multiple data of multiple datatype can be defined ,unordered, does not contain duplicate data,mutable(changable)
my_set = {"hello",15,35.5,True,None,"50"}
print(my_set)

