#  Membership operator : work with sequential data(group data,string), output: Boolean
# Check if a data exists in a sequential datatype

# in : if data exists output : True else output : False
# syntax: data in sequential_data

a = "Mindrisers"
print('d' in a)  #True

my_list = ['Boolean','check','if','data','exists','sequential']
print('data' in my_list) # True
print("hello" in my_list)  #False


# not in: if data exists output: False else output: True
print('data' not in my_list)  #False
print("hello" not in my_list)  #True


