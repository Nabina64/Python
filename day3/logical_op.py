# logical operators: used to combine conditional statements, output = boolean value(True or False)


# and: if all conditions are true then output will be true otherwise false
print(True and True)  # True
print(True and False and True)  # False


# or: if any one condition is true then output will be true otherwise false
print(True or False)  # True
print(False or False)  # False


# not: if condition is true then output will be false and vice versa
print(not(True))  # False
print(not(False))  # True