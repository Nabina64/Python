# Comparison Operator: operator used to compare values. Output: Boolean value (True or False)

# equal to (==) : check if given data are equal or not , if equal output: True, if not equal output: False

a = 10
b = 20

print(a == b)  # False

# not equal to (!=) : check if given data are not equal or not , if not equal output: True, if equal output: False

print(a != b)  # True

# greater than(>): if a is greater than b output: True, else output: False
print(a > b)   # False

# less than(<): if a is less than b output: True, else output: False
print(a < b)   # True

# greater than or equal to(>=): if a is greater than or equal to b output: True, else output: False
print(a >= b)  # False

# less than or equal to(<=): if a is less than or equal to b output: True, else output: False
print(a <= b)  # True